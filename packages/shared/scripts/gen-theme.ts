/**
 * Motion primitives for the renderer (03_motion_spec §5.5), as animation shorthands the API
 * Reference page (step 53) applies to Scalar elements it has verified in the running renderer.
 * Reduced motion sets every shorthand to `none` (03M §5.5, §8).
 */
export const scalarMotionVariables = {
  /** Response status chip pops once: scale 0.9 → 1 over `base` (240 ms). */
  '--dems-scalar-pop': `dems-pop ${motion.duration.base}ms ${cubicBezier(motion.easing.luxe)} 1 both`,
  /** SIMULATED badge shimmers once when a response arrives: `ambient` (1,200 ms). */
  '--dems-scalar-sheen': `dems-sheen ${motion.duration.ambient}ms ${cubicBezier(motion.easing.standard)} 1 both`,
  /** Operation chevron rotates 90°: `fast` (160 ms), `standard`. */
  '--dems-scalar-chevron-transition': `transform ${motion.duration.fast}ms ${cubicBezier(motion.easing.standard)}`,
} as const;

function varDecls(vars: Readonly<Record<string, string>>): Decl[] {
  return Object.entries(vars).map(([name, value]) => [name, value] as const);
}

export function generateScalarTheme(): string {
  const root: Decl[] = [...varDecls(scalarRootVariables), ...varDecls(scalarMotionVariables)];
  const modes: Decl[] = [['color-scheme', 'dark'], ...varDecls(scalarModeVariables)];
  const reduced: Decl[] = Object.keys(scalarMotionVariables).map((name) => [name, 'none'] as const);
  return [
    GENERATED_HEADER,
    '/* Scalar API Reference (01_specs §14.9): pass as `customCss`. Unlayered, so it wins over',
    '   Scalar\'s @layer scalar-base / scalar-theme defaults. Dark only (D16): .light-mode carries',
    '   identical values. Inter and JetBrains Mono only; Orbitron never appears inside the renderer. */',
    '',
    block([':root'], root),
    '',
    block(['.light-mode,', '.dark-mode'], modes),
    '',
    '@keyframes dems-pop {',
    '  from { transform: scale(0.9); }',
    '  to { transform: scale(1); }',
    '}',
    '',
    '@keyframes dems-sheen {',
    '  from { background-position: 200% 0; }',
    '  to { background-position: -200% 0; }',
    '}',
    '',
    '@media (prefers-reduced-motion: reduce) {',
    block([':root'], reduced, '  '),
    '}',
    '',
  ].join('\n');
}

export function generateTheme(): { web: string; native: string; scalar: string } {
  return { web: generateWebTheme(), native: generateNativeTheme(), scalar: generateScalarTheme() };
}

export const THEME_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'theme');
export const WEB_THEME_PATH = resolve(THEME_DIR, 'heroui-web.css');
export const NATIVE_THEME_PATH = resolve(THEME_DIR, 'heroui-native.css');
export const SCALAR_THEME_PATH = resolve(THEME_DIR, 'scalar.css');

function main(): void {
  const { web, native, scalar } = generateTheme();
  mkdirSync(THEME_DIR, { recursive: true });
  writeFileSync(WEB_THEME_PATH, web);
  writeFileSync(NATIVE_THEME_PATH, native);
  writeFileSync(SCALAR_THEME_PATH, scalar);
  console.log(`wrote ${WEB_THEME_PATH} (${web.length} bytes)`);
  console.log(`wrote ${NATIVE_THEME_PATH} (${native.length} bytes)`);
  console.log(`wrote ${SCALAR_THEME_PATH} (${scalar.length} bytes)`);
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  main();
}
