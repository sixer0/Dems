/**
 * Theme generator (masterplan/01_specs.md §2.9).
 *
 * Reads the single token source (src/tokens/tokens.ts) and writes:
 *   theme/heroui-web.css     HeroUI v3 (web): unlayered variable block + Tailwind @theme
 *   theme/heroui-native.css  HeroUI Native (Uniwind): @layer theme { :root { @variant … } } + @theme
 *
 * Both outputs are committed; test/theme.test.ts fails on any drift.
 * Run: `npm run build -w @dems/shared` (or `npm run theme:gen` at the root).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  elevation,
  extraColors,
  fontFamily,
  kitColors,
  kitShadows,
  kitSoft,
  radius,
  typography,
  type TypeStyle,
} from '../src/tokens/tokens';

export const GENERATED_HEADER =
  '/* GENERATED by packages/shared/scripts/gen-theme.ts from src/tokens/tokens.ts. Do not edit. */';

type Decl = readonly [name: string, value: string];

function block(selectorLines: string[], decls: readonly Decl[], indent = ''): string {
  const inner = decls.map(([name, value]) => `${indent}  ${name}: ${value};`).join('\n');
  return `${selectorLines.map((s) => indent + s).join('\n')} {\n${inner}\n${indent}}`;
}

function rem(px: number): string {
  return `${px / 16}rem`;
}

/**
 * `--text-*` sub-properties. Weights are emitted for the web only: on React Native every weight
 * is its own font family (`--font-bold` etc.), and a font-weight on top of a bold family would
 * be synthesised a second time on Android.
 */
function typeDecls(includeWeight: boolean): Decl[] {
  const out: Decl[] = [];
  for (const [name, style] of Object.entries(typography) as [string, TypeStyle][]) {
    out.push([`--text-${name}`, rem(style.size)]);
    out.push([`--text-${name}--line-height`, rem(style.lineHeight)]);
    if (style.letterSpacing !== 0) out.push([`--text-${name}--letter-spacing`, `${style.letterSpacing}em`]);
    if (includeWeight && style.weight !== 400) out.push([`--text-${name}--font-weight`, String(style.weight)]);
  }
  return out;
}

function glowDecls(): Decl[] {
  return [
    ['--shadow-glow-1', elevation[1]],
    ['--shadow-glow-2', elevation[2]],
    ['--shadow-glow-3', elevation[3]],
  ];
}

function extraColorDecls(): Decl[] {
  return Object.entries(extraColors).map(([name, hex]) => [`--color-${name}`, hex] as const);
}

function kitColorDecls(): Decl[] {
  return Object.entries(kitColors).map(([name, hex]) => [`--${name}`, hex] as const);
}

function shadowDecls(): Decl[] {
  return Object.entries(kitShadows).map(([name, value]) => [`--${name}`, value] as const);
}

export function generateWebTheme(): string {
  const softDecls: Decl[] = [];
  for (const [name, soft] of Object.entries(kitSoft)) {
    softDecls.push([`--${name}-soft`, soft.soft]);
    softDecls.push([`--${name}-soft-foreground`, soft.foreground]);
  }
  const vars: Decl[] = [
    ['color-scheme', 'dark'],
    ...kitColorDecls(),
    ...softDecls,
    ['--radius', radius.base],
    ['--field-radius', radius.field],
    ...shadowDecls(),
  ];
  const theme: Decl[] = [
    ...extraColorDecls(),
    ['--font-display', fontFamily.web.display],
    ['--font-sans', fontFamily.web.sans],
    ['--font-mono', fontFamily.web.mono],
    ...typeDecls(true),
    ...glowDecls(),
  ];
  return [
    GENERATED_HEADER,
    '/* HeroUI v3 (web). Dark only (D16). The variable block is unlayered, so it wins over',
    '   HeroUI\'s layer(theme) values; import it right after "@heroui/styles". */',
    '',
    block([':root,', '.dark,', '[data-theme="dark"]'], vars),
    '',
    block(['@theme'], theme),
    '',
  ].join('\n');
}

export function generateNativeTheme(): string {
  const variantDecls: Decl[] = [
    ...kitColorDecls(),
    ['--font-normal', `'${fontFamily.native.normal}'`],
    ['--font-medium', `'${fontFamily.native.medium}'`],
    ['--font-semibold', `'${fontFamily.native.semibold}'`],
    ['--font-bold', `'${fontFamily.native.bold}'`],
    ...shadowDecls(),
  ];
  const softDecls: Decl[] = [];
  for (const [name, soft] of Object.entries(kitSoft)) {
    softDecls.push([`--color-${name}-soft`, soft.soft]);
    softDecls.push([`--color-${name}-soft-foreground`, soft.foreground]);
  }
  const theme: Decl[] = [
    // HeroUI Native declares --radius/--field-radius in @theme (not per variant), so they are overridden here.
    ['--radius', radius.base],
    ['--field-radius', radius.field],
    // HeroUI Native derives soft colours with color-mix inside its own @theme (V38); override at --color-* level.
    ...softDecls,
    ...extraColorDecls(),
    ['--font-display', `'${fontFamily.native.display}'`],
    ['--font-mono', `'${fontFamily.native.mono}'`],
    ...typeDecls(false),
    ...glowDecls(),
  ];
  const dark = block(['@variant dark'], variantDecls, '    ');
  const light = block(['@variant light'], variantDecls, '    ');
  return [
    GENERATED_HEADER,
    '/* HeroUI Native (Uniwind). Dark only (D16): the light variant carries identical values so',
    '   an OS light mode cannot flip the theme. Import it right after "heroui-native/styles". */',
    '',
    '@layer theme {',
    '  :root {',
    dark,
    '',
    light,
    '  }',
    '}',
    '',
    block(['@theme'], theme),
    '',
  ].join('\n');
}

export function generateTheme(): { web: string; native: string } {
  return { web: generateWebTheme(), native: generateNativeTheme() };
}

export const THEME_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'theme');
export const WEB_THEME_PATH = resolve(THEME_DIR, 'heroui-web.css');
export const NATIVE_THEME_PATH = resolve(THEME_DIR, 'heroui-native.css');

function main(): void {
  const { web, native } = generateTheme();
  mkdirSync(THEME_DIR, { recursive: true });
  writeFileSync(WEB_THEME_PATH, web);
  writeFileSync(NATIVE_THEME_PATH, native);
  console.log(`wrote ${WEB_THEME_PATH} (${web.length} bytes)`);
  console.log(`wrote ${NATIVE_THEME_PATH} (${native.length} bytes)`);
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  main();
}
