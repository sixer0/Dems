// Local Expo config plugin: cleartext to the loopback Core link ONLY (M3-02 R2, register L10, ruling RT-2, D163).
//
// The tablet reaches the Core at `ws://127.0.0.1:4420/ws` and `http://127.0.0.1:4420` (adb reverse / USB).
// The React Native Gradle plugin sets `usesCleartextTraffic=false` for `release`, so a release build refuses
// that link. Instead of opening every host (`usesCleartextTraffic=true`, rejected in I63 §3.2), this plugin
// adds a domain-scoped Android network security config:
// - `<base-config cleartextTrafficPermitted="false">` for every other host;
// - `<domain-config cleartextTrafficPermitted="true">` for exactly `127.0.0.1` and `localhost`, no subdomains.
// `apps/mobile/android/` is regenerated by `expo prebuild`, so the plugin re-applies both parts on every
// prebuild (idempotent: the marker is checked first):
// - `android:networkSecurityConfig="@xml/network_security_config"` on `<application>` (withAndroidManifest);
// - `android/app/src/main/res/xml/network_security_config.xml` (withDangerousMod).
// It never sets `android:usesCleartextTraffic`, and it refuses to overwrite a config it did not write.
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const MARKER = '@dems-loopback-cleartext';
const XML_RESOURCE = '@xml/network_security_config';
const XML_RELATIVE_PATH = 'app/src/main/res/xml/network_security_config.xml';
const LOOPBACK_DOMAINS = Object.freeze(['127.0.0.1', 'localhost']);

const NETWORK_SECURITY_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- ${MARKER}: generated by apps/mobile/plugins/with-dems-loopback-cleartext.js (M3-02, L10, RT-2). Do not edit here. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
${LOOPBACK_DOMAINS.map((d) => `        <domain includeSubdomains="false">${d}</domain>`).join('\n')}
    </domain-config>
</network-security-config>
`;

/** Points `<application>` at the loopback config; a second run leaves the manifest unchanged. */
function applyLoopbackCleartextManifest(androidManifest) {
  const app = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  app.$ = app.$ || {};
  const current = app.$['android:networkSecurityConfig'];
  if (current !== undefined && current !== XML_RESOURCE) {
    throw new Error(`with-dems-loopback-cleartext: <application> already uses ${current}; refusing to replace it.`);
  }
  if (app.$['android:usesCleartextTraffic'] === 'true') {
    throw new Error('with-dems-loopback-cleartext: the main manifest allows cleartext to every host; remove usesCleartextTraffic.');
  }
  app.$['android:networkSecurityConfig'] = XML_RESOURCE;
  return androidManifest;
}

/** Returns the config file contents; refuses a file at that path that this plugin did not write. */
function networkSecurityXmlFor(existing) {
  if (existing != null && !existing.includes(MARKER)) {
    throw new Error(`with-dems-loopback-cleartext: ${XML_RELATIVE_PATH} exists without the ${MARKER} marker; refusing to overwrite it.`);
  }
  return NETWORK_SECURITY_XML;
}

/** Writes the config file under the generated `android/` root; unchanged contents are not rewritten. */
function writeNetworkSecurityXml(platformProjectRoot) {
  const file = path.join(platformProjectRoot, XML_RELATIVE_PATH);
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  const next = networkSecurityXmlFor(existing);
  if (existing !== next) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, next);
  }
  return file;
}

function withDemsLoopbackCleartext(config) {
  config = withAndroidManifest(config, (mod) => {
    mod.modResults = applyLoopbackCleartextManifest(mod.modResults);
    return mod;
  });
  return withDangerousMod(config, [
    'android',
    async (mod) => {
      writeNetworkSecurityXml(mod.modRequest.platformProjectRoot);
      return mod;
    },
  ]);
}

module.exports = withDemsLoopbackCleartext;
module.exports.applyLoopbackCleartextManifest = applyLoopbackCleartextManifest;
module.exports.networkSecurityXmlFor = networkSecurityXmlFor;
module.exports.writeNetworkSecurityXml = writeNetworkSecurityXml;
module.exports.MARKER = MARKER;
module.exports.XML_RESOURCE = XML_RESOURCE;
module.exports.XML_RELATIVE_PATH = XML_RELATIVE_PATH;
module.exports.LOOPBACK_DOMAINS = LOOPBACK_DOMAINS;
module.exports.NETWORK_SECURITY_XML = NETWORK_SECURITY_XML;
