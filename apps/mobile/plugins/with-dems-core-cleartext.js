// Local Expo config plugin: cleartext http/ws so the tablet reaches a user-configured LAN Core
// (row 237, D263; supersedes row 176's loopback-only config, RT-2/D163).
//
// Why: the Core address is now a user setting (row 236, default 127.0.0.1:4420), for example
// `http://192.168.0.29:4420` and `ws://192.168.0.29:4420/ws`. The React Native Gradle plugin sets
// `usesCleartextTraffic=false` for `release`, and Android's network security config cannot permit
// cleartext by IP range, so the only way to reach a LAN Core over http/ws in a release build is
// `<base-config cleartextTrafficPermitted="true">`.
//
// RISK: the release build may send cleartext (http, ws) to ANY host, not only the Core. Compensations:
// - row 236 refuses public IPv4 addresses in the app: the Core address must be private, loopback or
//   link-local IPv4 (or a hostname), port 1-65535, no scheme or path;
// - the device credential is bound to the address: changing the address forgets the stored credential,
//   so a credential is never sent to another Core;
// - the DEMS LAN is a closed interview-room network;
// - TLS to the Core is the proper fix and stays open as residual R263-TLS (user decision list, security review).
//
// The `127.0.0.1` / `localhost` domain-config is kept: it is harmless under a permissive base-config and it
// documents the adb-reverse / USB loopback path (the default address).
// `apps/mobile/android/` is regenerated by `expo prebuild`, so the plugin re-applies both parts on every
// prebuild (idempotent: the marker is checked first):
// - `android:networkSecurityConfig="@xml/network_security_config"` on `<application>` (withAndroidManifest);
// - `android/app/src/main/res/xml/network_security_config.xml` (withDangerousMod).
// It never sets `android:usesCleartextTraffic`, adds no `debug-overrides` and changes no trust anchors,
// and it refuses to overwrite a config it did not write.
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const PLUGIN = 'with-dems-core-cleartext';
const MARKER = '@dems-core-cleartext';
// Row 176 wrote this marker; a file carrying it is ours too and may be replaced (prebuild without --clean).
const LEGACY_MARKERS = Object.freeze(['@dems-loopback-cleartext']);
const XML_RESOURCE = '@xml/network_security_config';
const XML_RELATIVE_PATH = 'app/src/main/res/xml/network_security_config.xml';
const LOOPBACK_DOMAINS = Object.freeze(['127.0.0.1', 'localhost']);

const NETWORK_SECURITY_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- ${MARKER}: generated by apps/mobile/plugins/${PLUGIN}.js (row 237, D263). Do not edit here. -->
<!-- Cleartext is permitted so the user-configured LAN Core is reachable; the app restricts the Core address to private, loopback and link-local (row 236). TLS: residual R263-TLS. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="true" />
    <domain-config cleartextTrafficPermitted="true">
${LOOPBACK_DOMAINS.map((d) => `        <domain includeSubdomains="false">${d}</domain>`).join('\n')}
    </domain-config>
</network-security-config>
`;

/** Points `<application>` at the config; a second run leaves the manifest unchanged. */
function applyCoreCleartextManifest(androidManifest) {
  const app = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  app.$ = app.$ || {};
  const current = app.$['android:networkSecurityConfig'];
  if (current !== undefined && current !== XML_RESOURCE) {
    throw new Error(`${PLUGIN}: <application> already uses ${current}; refusing to replace it.`);
  }
  if (app.$['android:usesCleartextTraffic'] === 'true') {
    throw new Error(`${PLUGIN}: the main manifest sets usesCleartextTraffic; remove it, the network security config governs cleartext.`);
  }
  app.$['android:networkSecurityConfig'] = XML_RESOURCE;
  return androidManifest;
}

/** Returns the config file contents; refuses a file at that path that this plugin (or row 176) did not write. */
function networkSecurityXmlFor(existing) {
  if (existing != null && ![MARKER, ...LEGACY_MARKERS].some((m) => existing.includes(m))) {
    throw new Error(`${PLUGIN}: ${XML_RELATIVE_PATH} exists without the ${MARKER} marker; refusing to overwrite it.`);
  }
  return NETWORK_SECURITY_XML;
}

/** Writes the config file under the generated `android/` root; unchanged contents are not rewritten. */
function writeNetworkSecurityXml(platformProjectRoot) {
  const file = path.join(platformProjectRoot, XML_RELATIVE_PATH);
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  const next = networkSecurityXmlFor(existing);
  if (existing !== next) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, next);
  }
  return file;
}

function withDemsCoreCleartext(config) {
  config = withAndroidManifest(config, (mod) => {
    mod.modResults = applyCoreCleartextManifest(mod.modResults);
    return mod;
  });
  return withDangerousMod(config, [
    'android',
    async (mod) => {
      writeNetworkSecurityXml(mod.modRequest.platformProjectRoot);
      return mod;
    },
  ]);
}

module.exports = withDemsCoreCleartext;
module.exports.applyCoreCleartextManifest = applyCoreCleartextManifest;
module.exports.networkSecurityXmlFor = networkSecurityXmlFor;
module.exports.writeNetworkSecurityXml = writeNetworkSecurityXml;
module.exports.MARKER = MARKER;
module.exports.LEGACY_MARKERS = LEGACY_MARKERS;
module.exports.XML_RESOURCE = XML_RESOURCE;
module.exports.XML_RELATIVE_PATH = XML_RELATIVE_PATH;
module.exports.LOOPBACK_DOMAINS = LOOPBACK_DOMAINS;
module.exports.NETWORK_SECURITY_XML = NETWORK_SECURITY_XML;
