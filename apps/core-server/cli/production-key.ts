/**
 * THE PROCESS ENTRY of the production key command (task 4 row 206, package X1-1; decision U19):
 *
 *   npm run evidence:production-key -w @dems/core-server -- --data-dir <absolute directory>
 *
 * What the command DOES is `cli/production-key-command.ts` (the arguments, the directory rule, the
 * typed values, the provisioning through the signer store, the real load, the two records). This
 * file is only what a process entry is: the arguments of the process, its output stream, its exit
 * status, the host clock, the numeric id of the calling user and the terminal the two values and
 * the confirmation word are typed at. Both files lie OUTSIDE `src/`, as the receiver's entry does:
 * the server never loads them.
 *
 * NOTHING SECRET IS TYPED OR PRINTED. The two typed values are public (they end up in the
 * certificate) and are echoed; the key is generated by the signer store and never reaches this
 * process's output. The command reads NO environment variable. Without a terminal on standard
 * input no line is read and the command refuses (`NOT_A_TERMINAL`): it is run by a person at the
 * Core host, as the OS user the Core runs as.
 *
 * Exit status: 0 provisioned, 1 refused or failed, 2 usage.
 */
import { createInterface } from 'node:readline';
import { ProductionKeyExit, runProductionKeyCommand, type ProductionKeyPorts } from './production-key-command';

/** The ports of a real run: this process, its terminal and the host clock. */
export function terminalPorts(): ProductionKeyPorts {
  return {
    now: () => Date.now(),
    uid: () => (typeof process.getuid === 'function' ? process.getuid() : -1),
    out: (line) => void process.stdout.write(`${line}\n`),
    ask: (prompt) =>
      new Promise<string | null>((settle) => {
        if (process.stdin.isTTY !== true) return settle(null);
        const reader = createInterface({ input: process.stdin, output: process.stdout, terminal: true });
        let answered = false;
        reader.question(prompt, (line) => {
          answered = true;
          reader.close();
          settle(line);
        });
        // The input ended (Ctrl-D) or the line was abandoned (Ctrl-C): no line was typed.
        reader.once('close', () => {
          if (!answered) settle(null);
        });
      }),
  };
}

const invoked = process.argv[1] !== undefined && /production-key\.[cm]?[jt]s$/.test(process.argv[1]);
if (invoked) {
  runProductionKeyCommand(process.argv.slice(2), terminalPorts()).then(
    (run) => {
      process.exitCode = run.code;
    },
    () => {
      process.stderr.write('evidence:production-key: FAILED, the command could not run\n');
      process.exitCode = ProductionKeyExit.REFUSED;
    },
  );
}
