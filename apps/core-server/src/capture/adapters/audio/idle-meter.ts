/**
 * THE IDLE MICROPHONE METERS (decisions D51/D53; row 91c): the levels of the PRIMARY and the STANDBY
 * microphone on the Devices & Inputs page while NO session is active.
 *
 * During a session the levels come from the capture worker's telemetry. Outside one nothing reads a
 * card, so this unit does, ON REQUEST ONLY: a page that shows the meters takes a LEASE (`hold`), of
 * `IDLE_METER_LEASE_MS`, and renews it while it is shown. While at least one lease is held, no session
 * is active and the unit is not suspended, it starts, for each DISTINCT CARD that holds the PRIMARY or
 * the STANDBY input of the selector in force, ONE helper - at most `IDLE_METER_HELPERS_MAX` - that
 * reads ALL native channels of the card through the EXISTING shared capture and writes them to its own
 * standard output (`linuxMicLevelArguments`). The samples are cut into windows by `idle-level.ts` and
 * the levels of the card's selected inputs are handed to `publish`. Nothing is written but the
 * shared-capture configuration, nothing is recorded, nothing is kept.
 *
 * THE SAME CARD AND THE SAME SHARED CAPTURE as a session's: the stored row of each input is matched to
 * a FRESH listing by `identifyRegisteredCard` of the production adapter (the USB id plus the serial,
 * never a card index); the configuration is generated by `ensureAlsaConfig` from `sharedCaptureOfCard`
 * of the same card at the transport's rate, so its entry - and the IPC key of the card - is the one a
 * session writes. The helper is started UNDER THE GUARD through the production door, with the guard's
 * vector of the production adapter (`guardedArguments`) and the configuration's one environment key,
 * exactly as the adapter starts its own. It is stopped the adapter's way: the end of the guard's input
 * first, a signal only when that is not obeyed.
 *
 * WHAT IS NOT DONE. A card that is not there, not the registered unit, of a guessed channel count or
 * of another rate is NOT READ: its inputs get no level (the page shows NO SIGNAL), no fault is raised
 * and nothing is retried before the next `hold`. A helper that ends by itself is not started again
 * before the next `hold` either. Nothing here touches a session, a fault or the store.
 *
 * THE ORDER WITH A SESSION. `stopAndWait` is called by the composition when a session is CREATED and
 * before the pre-check opens a card: it suspends the unit, waits for a start in flight and resolves
 * when every helper has ENDED (reaped by the door). `resume` is called after the session is SEALED: a
 * lease still held starts the helpers again. `sessionActive` is asked as well, so a session the unit
 * was not told of (a Core that restarted into one) is never read beside.
 *
 * It does not log (the capture folder logs in one place): what went wrong is told to `onNotice` as a
 * code and a short detail word, never a value. Neither `hold` nor `resume` throws.
 *
 * NOT PROVEN ON THIS HOST (unit tests with a door that starts nothing): the pinned helper on the
 * bench's card through the shared capture beside a session's later open of the same card.
 */
import { helperProgramRefusal } from '../local/helper-program';
import { linuxMicLevelArguments } from '../local/mic-helper-args';
import { inspectProgram, type ProgramInspector } from '../local/process-door';
import { MIC_TRANSPORTS } from '../mic-transport';
import { startProductionProcess, type ProductionDoor, type ProductionEnvironment, type ProductionProcess } from '../production-door';
import type { CaptureTimers } from '../../types';
import { ensureAlsaConfig, sharedCaptureOfCard, type AlsaConfigWriter, type SharedCaptureCard } from './alsa-config';
import { CardFactsSource, type CaptureCard, type CardEnumerator, type CardListing } from './card-listing';
import { createIdleLevelReader, type InputWindowLevel } from './idle-level';
import { guardedArguments, identifyRegisteredCard, isRegisteredAudioInput, type RegisteredAudioInput } from './usb-audio-production';

/** A lease lives this long from its last `hold`. */
export const IDLE_METER_LEASE_MS = 30_000;
/** At most this many helpers run: one per card of the two inputs the worker's role lane names (D61, 2026-11-04: the transcription pair; the selector plane carries four channels). */
export const IDLE_METER_HELPERS_MAX = 2;

// D61 (2026-11-04): the roles are the worker's two-role lane's names of the transcription pair (channels 1 and 2 of the
// numbered selector plane); the idle meters report on that lane until the worker's own D61 wave. The selector names channels.
export const IdleMeterRole = { PRIMARY: 'PRIMARY', STANDBY: 'STANDBY' } as const;
export type IdleMeterRole = (typeof IdleMeterRole)[keyof typeof IdleMeterRole];

/** One input of the selector in force: the microphone (`MIC-NN`) and its legacy role name on the worker's two-role lane (D61, 2026-11-04). Only PRIMARY and STANDBY are read. */
export interface IdleMeterInput {
  readonly deviceId: string;
  readonly role: IdleMeterRole;
}

/** What `publish` is handed per window of one card: the shape of a telemetry level of the worker, with a number always. */
export interface IdleMeterLevel {
  readonly deviceId: string;
  readonly role: IdleMeterRole;
  readonly dbfs: number;
  readonly clipped: boolean;
}

export const IdleMeterNoticeCode = {
  /** The selector in force could not be read. */
  SELECTION_FAILED: 'IDLE_METER_SELECTION_FAILED',
  /** The stored row of an input could not be read or is not of its shape. */
  INPUT_NOT_REGISTERED: 'IDLE_METER_INPUT_NOT_REGISTERED',
  /** The cards could not be listed. */
  LISTING_FAILED: 'IDLE_METER_LISTING_FAILED',
  /** The registered card of an input is not read: the detail word says why (the refusal of the match, or the rule). */
  CARD_NOT_READ: 'IDLE_METER_CARD_NOT_READ',
  /** The shared-capture configuration could not be made. */
  CONFIG_REFUSED: 'IDLE_METER_CONFIG_REFUSED',
  /** The helper or the guard is refused by the program path rule. */
  PROGRAM_REFUSED: 'IDLE_METER_PROGRAM_REFUSED',
  /** The door did not start the guard. */
  HELPER_NOT_STARTED: 'IDLE_METER_HELPER_NOT_STARTED',
  /** A helper ended without being asked to. It is not started again before the next `hold`. */
  HELPER_ENDED: 'IDLE_METER_HELPER_ENDED',
  /** A helper did not end when its input ended: it was signalled. */
  HELPER_SIGNALLED: 'IDLE_METER_HELPER_SIGNALLED',
} as const;
export type IdleMeterNoticeCode = (typeof IdleMeterNoticeCode)[keyof typeof IdleMeterNoticeCode];

export interface IdleMeterNotice {
  readonly code: IdleMeterNoticeCode;
  /** The microphone the notice is about (`MIC-NN`), or null for one about the unit. */
  readonly deviceId: string | null;
  /** A short code word (`CARD_ABSENT`, `EXIT_1`), never a value of a card, a path or a program's output. */
  readonly detail: string;
}

export interface IdleMeterLimits {
  /** After the end of the guard's input: this long, then SIGTERM. */
  readonly stopGraceMs: number;
  /** After SIGTERM: this long, then SIGKILL. */
  readonly killGraceMs: number;
}

/** The production adapter's figures (`USB_AUDIO_LIMITS`). */
export const IDLE_METER_LIMITS: IdleMeterLimits = Object.freeze({ stopGraceMs: 3_000, killGraceMs: 2_000 });

export interface IdleMetersDeps {
  /** The PRIMARY and the STANDBY input of the selector in force, read at every start. Another role is ignored. */
  readonly selection: () => Promise<readonly IdleMeterInput[]>;
  /** The stored row of a microphone (the production adapter's reader), or null when it has none. */
  readonly registered: (deviceId: string) => Promise<RegisteredAudioInput | null>;
  /** The card listing. Every start lists the cards again; nothing of a listing is kept. */
  readonly cards: CardEnumerator;
  /** The writer of the shared-capture configuration, bound to `runDir` (the production adapter's). */
  readonly configWriter: AlsaConfigWriter;
  /** The helper program: an absolute path of the configuration. */
  readonly helperProgram: string;
  /** The guard program (`DEMS_CAPTURE_GUARD`). The helper is started by it, never directly. */
  readonly guardProgram: string;
  /** `<dataDir>/run/capture`: the configuration lives below it. */
  readonly runDir: string;
  readonly timers: CaptureTimers;
  /** The clock of the lease's answer (epoch ms). */
  readonly now: () => number;
  /** True while a session is active (CREATE to SEALED): no helper starts and no level is published. */
  readonly sessionActive: () => boolean;
  /** Handed the levels of one card per window. The observer must not throw; a throw is dropped. */
  readonly publish: (levels: readonly IdleMeterLevel[]) => void;
  /** Told what went wrong, as a code. The observer must not throw; a throw is dropped. */
  readonly onNotice?: (notice: IdleMeterNotice) => void;
  /** The production door. Default: the real one. A test passes one that starts nothing. */
  readonly door?: ProductionDoor;
  readonly inspect?: ProgramInspector;
  readonly limits?: Partial<IdleMeterLimits>;
}

export interface IdleMeters {
  /** Takes or renews the lease of one operator. Starts the helpers when none runs for a selected card. Never throws. */
  hold(operatorId: string): { expiresAt: number };
  /** Suspends the unit and resolves when no helper is alive (a start in flight is waited for first). */
  stopAndWait(): Promise<void>;
  /** Ends the suspension; a lease still held starts the helpers again. Never throws. */
  resume(): void;
  /** Ends every lease and every helper for good. */
  close(): Promise<void>;
}

const DETAIL_WORD = /^[A-Z][A-Z0-9_]{0,47}$/;
const NO_DETAIL = 'NONE';
const OPERATOR_ID_MAX = 128;

function detailOf(error: unknown): string {
  const carried = error as { what?: unknown; reason?: unknown; code?: unknown } | null;
  for (const word of [carried?.what, carried?.reason, carried?.code]) if (typeof word === 'string' && DETAIL_WORD.test(word)) return word;
  return NO_DETAIL;
}

/** One card to read: the card of the listing, its shared-capture entry and the inputs of it that are selected. */
interface CardPlan {
  readonly key: string;
  /** The card and the inputs read of it, as one text: a running helper of another signature is replaced. */
  readonly signature: string;
  readonly card: CaptureCard;
  readonly shared: SharedCaptureCard;
  readonly inputs: { readonly deviceId: string; readonly role: IdleMeterRole; readonly inputNumber: number }[];
}

interface Running {
  readonly helper: ProductionProcess;
  readonly signature: string;
  stopping: boolean;
}

const cardKey = (card: Pick<CaptureCard, 'cardIndex' | 'deviceIndex'>): string => `${String(card.cardIndex)}:${String(card.deviceIndex)}`;

export function createIdleMeters(deps: IdleMetersDeps): IdleMeters {
  const limits: IdleMeterLimits = { ...IDLE_METER_LIMITS, ...deps.limits };
  const door = deps.door ?? startProductionProcess;
  const inspect = deps.inspect ?? inspectProgram;
  const { timers } = deps;
  const rateHz = MIC_TRANSPORTS.PCM_FIFO.sampleRateHz;

  /** The leases, by operator: when each ends, and the timer that ends it. */
  const leases = new Map<string, { expiresAt: number; cancel: () => void }>();
  /** The helpers that run, by card. */
  const running = new Map<string, Running>();
  /** The ends of the helpers being stopped: a new start waits for them. */
  const stopping = new Set<Promise<unknown>>();
  let starting: Promise<void> | null = null;
  let suspended = false;
  let closed = false;
  /** Moves on every suspension and at the close: a start of an older generation starts nothing more. */
  let generation = 0;

  const notice = (code: IdleMeterNoticeCode, deviceId: string | null, detail: string = NO_DETAIL): void => {
    try {
      deps.onNotice?.(Object.freeze({ code, deviceId, detail: DETAIL_WORD.test(detail) ? detail : NO_DETAIL }));
    } catch {
      // An observer never changes what the unit does.
    }
  };

  const sessionActive = (): boolean => {
    try {
      return deps.sessionActive();
    } catch {
      // When it cannot be said, a session is taken to be active: a card is then never read beside one.
      return true;
    }
  };

  const mayRun = (): boolean => !closed && !suspended && leases.size > 0 && !sessionActive();

  /** The adapter's stop: the end of the guard's input first, a signal only when that was not obeyed. Resolves at the end. */
  function stop(key: string, entry: Running): Promise<unknown> {
    if (running.get(key) === entry) running.delete(key);
    if (entry.stopping) return entry.helper.ended;
    entry.stopping = true;
    if (!entry.helper.alive()) return entry.helper.ended;
    entry.helper.endInput();
    const cancelTerm = timers.after(limits.stopGraceMs, () => {
      notice(IdleMeterNoticeCode.HELPER_SIGNALLED, null);
      entry.helper.kill('SIGTERM');
    });
    const cancelKill = timers.after(limits.stopGraceMs + limits.killGraceMs, () => entry.helper.kill('SIGKILL'));
    const ended = entry.helper.ended.then(() => {
      cancelTerm();
      cancelKill();
      stopping.delete(ended);
    });
    stopping.add(ended);
    return ended;
  }

  function stopAll(): Promise<unknown> {
    return Promise.all([...running.entries()].map(([key, entry]) => stop(key, entry)));
  }

  /** The cards of the selected inputs, from ONE fresh listing; what is not read is told and left out. Null: the selection or the listing could not be read. */
  async function plan(): Promise<CardPlan[] | null> {
    let selected: readonly IdleMeterInput[];
    try {
      selected = await deps.selection();
    } catch (error) {
      notice(IdleMeterNoticeCode.SELECTION_FAILED, null, detailOf(error));
      return null;
    }
    // PRIMARY first, then STANDBY; one entry per microphone.
    const wanted: IdleMeterInput[] = [];
    for (const role of [IdleMeterRole.PRIMARY, IdleMeterRole.STANDBY]) {
      for (const input of selected) {
        if (input?.role !== role || typeof input.deviceId !== 'string' || wanted.some((taken) => taken.deviceId === input.deviceId)) continue;
        wanted.push({ deviceId: input.deviceId, role });
      }
    }
    if (wanted.length === 0) return [];

    const rows: { input: IdleMeterInput; stored: RegisteredAudioInput }[] = [];
    for (const input of wanted) {
      let row: RegisteredAudioInput | null;
      try {
        row = await deps.registered(input.deviceId);
      } catch (error) {
        notice(IdleMeterNoticeCode.INPUT_NOT_REGISTERED, input.deviceId, detailOf(error));
        continue;
      }
      if (!isRegisteredAudioInput(row) || row.deviceId !== input.deviceId) {
        notice(IdleMeterNoticeCode.INPUT_NOT_REGISTERED, input.deviceId);
        continue;
      }
      rows.push({ input, stored: row });
    }
    if (rows.length === 0) return [];

    let listing: CardListing;
    try {
      listing = await deps.cards.list();
    } catch (error) {
      notice(IdleMeterNoticeCode.LISTING_FAILED, null, detailOf(error));
      return null;
    }

    const plans = new Map<string, CardPlan>();
    for (const { input, stored } of rows) {
      const found = identifyRegisteredCard(listing, stored);
      if (!found.ok) {
        notice(IdleMeterNoticeCode.CARD_NOT_READ, input.deviceId, found.refusal);
        continue;
      }
      const { card } = found;
      if (card.factsSource === CardFactsSource.ASSUMED) {
        notice(IdleMeterNoticeCode.CARD_NOT_READ, input.deviceId, 'CARD_FACTS_UNKNOWN');
        continue;
      }
      if (stored.inputNumber > card.channelCount) {
        notice(IdleMeterNoticeCode.CARD_NOT_READ, input.deviceId, 'INPUT_BEYOND_CARD');
        continue;
      }
      let shared: SharedCaptureCard;
      try {
        shared = sharedCaptureOfCard(card, rateHz);
      } catch (error) {
        notice(IdleMeterNoticeCode.CONFIG_REFUSED, input.deviceId, detailOf(error));
        continue;
      }
      // A session refuses a card at another rate (the adapter's `CARD_RATE_UNSUPPORTED`): it is not read here either.
      if (shared.rateHz !== rateHz) {
        notice(IdleMeterNoticeCode.CARD_NOT_READ, input.deviceId, 'CARD_RATE_UNSUPPORTED');
        continue;
      }
      const key = cardKey(card);
      const known = plans.get(key);
      if (known !== undefined) {
        known.inputs.push({ deviceId: input.deviceId, role: input.role, inputNumber: stored.inputNumber });
        continue;
      }
      if (plans.size >= IDLE_METER_HELPERS_MAX) continue;
      plans.set(key, { key, signature: '', card, shared, inputs: [{ deviceId: input.deviceId, role: input.role, inputNumber: stored.inputNumber }] });
    }
    return [...plans.values()].map((entry) => ({ ...entry, signature: `${entry.key}|${String(entry.card.channelCount)}|${entry.inputs.map((input) => `${input.deviceId}:${input.role}:${String(input.inputNumber)}`).join(',')}` }));
  }

  function programsRefused(): string | null {
    const helper = helperProgramRefusal(inspect(deps.helperProgram));
    if (helper !== null) return `HELPER_${helper}`;
    const guard = helperProgramRefusal(inspect(deps.guardProgram));
    return guard === null ? null : `GUARD_${guard}`;
  }

  /** Starts a helper for every selected card that has none. Nothing of it throws. */
  async function start(asOf: number): Promise<void> {
    // A helper still ending holds its card; the new one starts after it.
    await Promise.all([...stopping]);
    if (asOf !== generation || !mayRun()) return;
    const cards = await plan();
    if (cards === null || asOf !== generation || !mayRun()) return;
    // A helper of a card that is no longer selected, or whose selected inputs changed, is stopped; the new plan replaces it.
    const replaced = [...running.entries()].filter(([key, entry]) => !cards.some((wanted) => wanted.key === key && wanted.signature === entry.signature));
    if (replaced.length > 0) await Promise.all(replaced.map(([key, entry]) => stop(key, entry)));
    if (asOf !== generation || !mayRun()) return;
    const fresh = cards.filter((entry) => !running.has(entry.key)).slice(0, Math.max(0, IDLE_METER_HELPERS_MAX - running.size));
    if (fresh.length === 0) return;
    const refused = programsRefused();
    if (refused !== null) {
      notice(IdleMeterNoticeCode.PROGRAM_REFUSED, null, refused);
      return;
    }
    // One entry per card that is read: the same entry, and the same key, as a session writes for that card.
    let environment: ProductionEnvironment;
    try {
      environment = (await ensureAlsaConfig(deps.configWriter, deps.runDir, cards.map((entry) => entry.shared))).environment;
    } catch (error) {
      notice(IdleMeterNoticeCode.CONFIG_REFUSED, null, detailOf(error));
      return;
    }
    if (asOf !== generation || !mayRun()) return;

    for (const entry of fresh) {
      let args: readonly string[];
      try {
        // INTEGERS ONLY, of the live listing: all native channels of the card; nothing is selected.
        args = linuxMicLevelArguments({ cardIndex: entry.card.cardIndex, deviceIndex: entry.card.deviceIndex, channelCount: entry.card.channelCount });
      } catch (error) {
        notice(IdleMeterNoticeCode.CONFIG_REFUSED, entry.inputs[0]?.deviceId ?? null, detailOf(error));
        continue;
      }
      const inputs = entry.inputs;
      const reader = createIdleLevelReader({
        channelCount: entry.card.channelCount,
        inputs: inputs.map((input) => input.inputNumber),
        onWindow: (levels: readonly InputWindowLevel[]) => {
          if (asOf !== generation || !mayRun()) return;
          const out: IdleMeterLevel[] = [];
          for (const level of levels) {
            const input = inputs.find((candidate) => candidate.inputNumber === level.inputNumber);
            if (input !== undefined) out.push(Object.freeze({ deviceId: input.deviceId, role: input.role, dbfs: level.dbfs, clipped: level.clipped }));
          }
          try {
            deps.publish(Object.freeze(out));
          } catch {
            // The observer's side never stops the reading.
          }
        },
      });
      const helper = door({ command: deps.guardProgram, args: guardedArguments(deps.helperProgram, args), env: environment, message: null, timers, onOutput: (chunk) => reader.push(chunk) });
      const own: Running = { helper, signature: entry.signature, stopping: false };
      running.set(entry.key, own);
      void helper.ended.then((exit) => {
        if (running.get(entry.key) === own) running.delete(entry.key);
        if (own.stopping) return;
        notice(IdleMeterNoticeCode.HELPER_ENDED, inputs[0]?.deviceId ?? null, exit.spawnFailed ? 'NOT_STARTED' : typeof exit.exitCode === 'number' ? `EXIT_${String(exit.exitCode)}` : (exit.signal ?? NO_DETAIL));
      });
      try {
        await helper.started;
      } catch (error) {
        notice(IdleMeterNoticeCode.HELPER_NOT_STARTED, inputs[0]?.deviceId ?? null, detailOf(error));
        continue;
      }
      // Suspended while the door was starting it: it ends at once.
      if (asOf !== generation || !mayRun()) void stop(entry.key, own);
    }
  }

  function ensure(): void {
    if (!mayRun() || starting !== null) return;
    const asOf = generation;
    const current: Promise<void> = start(asOf)
      .catch((error: unknown) => notice(IdleMeterNoticeCode.HELPER_NOT_STARTED, null, detailOf(error)))
      .finally(() => {
        if (starting === current) starting = null;
      });
    starting = current;
  }

  function endLease(operatorId: string): void {
    leases.delete(operatorId);
    if (leases.size === 0) void stopAll();
  }

  return {
    hold(operatorId) {
      const expiresAt = deps.now() + IDLE_METER_LEASE_MS;
      if (closed || typeof operatorId !== 'string' || operatorId === '' || operatorId.length > OPERATOR_ID_MAX) return { expiresAt };
      leases.get(operatorId)?.cancel();
      const cancel = timers.after(IDLE_METER_LEASE_MS, () => {
        if (leases.get(operatorId)?.cancel === cancel) endLease(operatorId);
      });
      leases.set(operatorId, { expiresAt, cancel });
      ensure();
      return { expiresAt };
    },

    async stopAndWait() {
      suspended = true;
      generation += 1;
      const inFlight = starting;
      if (inFlight !== null) await inFlight;
      await stopAll();
      await Promise.all([...stopping]);
    },

    resume() {
      if (closed) return;
      suspended = false;
      ensure();
    },

    async close() {
      closed = true;
      generation += 1;
      for (const lease of leases.values()) lease.cancel();
      leases.clear();
      const inFlight = starting;
      if (inFlight !== null) await inFlight;
      await stopAll();
      await Promise.all([...stopping]);
    },
  };
}
