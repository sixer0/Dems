// Task 4 row 226b (decision C69 (1); the finding of rows 225 / 226): a signer that was LOADED keeps
// its private key for as long as its process lives, and the commands that mark a key compromised or
// rotate it cannot see a process. So the signer itself asks the store again before EACH signature:
//
//   the compromise mark of its key id   present -> `KEY_COMPROMISED`, nothing is signed
//   the pointer (a signer loaded as THE ACTIVE key, i.e. without a key id)
//                                       another id -> `ACTIVE_KEY_CHANGED` (no switch without a restart)
//                                       cannot be taken -> `ACTIVE_KEY_POINTER_INVALID`
//   the store directory                 absent / reachable by others -> the codes of a load
//
// Nothing that was signed before is touched: the mark is ONE new file, every other entry of the
// store is byte-identical, and a signature made before the mark still verifies.
//
// SECRETS: every key is generated by this test in a temporary directory that `afterAll` removes
// and asserts gone. Nothing under the repository's data directory is named. Nothing is printed.
