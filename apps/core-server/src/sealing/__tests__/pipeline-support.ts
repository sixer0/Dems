// Test support of row 82: a RECORDED SESSION on disk as the capture side leaves it, and the ports
// of the sealing pipeline around it. Not a test file.
//
// WHAT IS REAL. The two RECORDING files are built box by box as the worker writes them (`ftyp`,
// `moov`, then `moof` + `mdat` per fragment, `mfhd` numbered 1, 2, 3 ..., a video run that carries
// its media time), in PLAINTEXT at `SESSION-<id>/VIDEO-0n.mp4`, with the rows of
// `recording_fragments` the worker's `FRAGMENT_CHECKPOINT` records give (digest and chain of those
// bytes). The pipeline seals them itself (ruling D147) with the PRODUCT cipher
// (`createFragmentSealer` of the credential store, row 84) under a session key of a real file key
// store. The signer is row 83's, on a throw-away key.
//
// WHAT IS NOT. The media (generated bytes, no decodable video), the capture worker (nothing was
// captured), the database (rows and the journal are kept in memory) and the engine (a recorder of
// the two INTERNAL actions). THE NONCE SOURCE IS A TEST DOUBLE: each fragment's nonce is derived
// from its position, so that two runs over the same recording write the same sealed bytes and
// their manifests can be compared; the product draws 96 random bits. Nothing here is evidence.
