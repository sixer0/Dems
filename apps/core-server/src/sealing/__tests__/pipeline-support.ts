const neverAsked: AssembledTranscriptSource = {
  assemble: async () => {
    throw new Error('a disabled transcript asks the transcriber nothing');
  },
  locate: () => {
    throw new Error('a disabled transcript has no files');
  },
  closeOut: async () => {
    throw new Error('a disabled transcript is not closed out');
  },
};

export function harnessOf(recording: Recording, options: HarnessOptions = {}): Harness {
  const journal = options.journal ?? memoryJournal();
  const log = memoryErrorLog();
  const clock = options.clock ?? manualClock(CLOCK_START);
  const signer = options.signer ?? throwAwaySigner();
  const engine: RecordedEngine = options.engine ?? { progress: [], sealed: [], completeCalls: 0, refuseProgress: false };
  const mirror = options.transcript?.mirror ?? createMemoryChunkMirror();
  const harness: Harness = {
    recording,
    journal,
    log,
    engine,
    clock,
    signer,
    hook: null,
    facts: sessionFacts(recording.sessionId, { ...(options.transcript === undefined ? {} : { sttSnapshot: options.transcript.snapshot }), ...options.facts }),
    anchors: () => {
      const last = engine.sealed.at(-1);
      if (last === undefined) throw new Error('nothing was sealed');
      return { evidenceId: harness.facts.evidenceId, sessionId: recording.sessionId, manifestSha256: last.input.manifestSha256, transcriptSha256: last.input.transcriptSha256, revisionCount: 0, trustedCertificateSha256: [signer.certificate.sha256] };
    },
    again: () => createSealingPipeline({ ...harness.ports, ...(harness.hook === null ? {} : { hook: harness.hook }) }),
    pipeline: undefined as unknown as SealingPipeline,
    ports: undefined as unknown as SealingPorts,
  };
  const ports: SealingPorts = {
    journal,
    fragments: {
      // D60 (2026-11-04): the pipeline's first-run probe (D84) reads every possible track - VIDEO-01..04 - and the row store answers NONE for a track the session does not hold; the fake says the same for a track this two-file fixture lacks.
      // Row 153 (D118 H-2): the eight tracks of 0044 - a camera file's rows or a pair audio file's.
      read: async (_sessionId, trackId) => (recording.rowsOf(trackId) ?? []).map((row) => ({ ...row })),
      async insertMissing(rows) {
        let inserted = 0;
        for (const row of rows) {
          const stored = recording.rowsOf(row.trackId);
          if (stored === undefined) throw new Error(`the fixture holds no track ${row.trackId}`);
          if (stored.some((existing) => existing.seq === row.seq)) continue;
          stored.push({ ...row });
          inserted += 1;
        }
        return { inserted, alreadyStored: rows.length - inserted };
      },
    },
    sealer: recording.sealer,
    opener: recording.opener,
    session: { read: async (sessionId) => (sessionId === recording.sessionId ? harness.facts : null) },
    transcript: {
      finalize: (input) => finalizeTranscript(input, { transcript: options.transcript?.seam ?? neverAsked, chunkRows: mirror, files: createTranscriptFileReader(), journal, log, now: clock.now, timer: clock.timer }),
    },
    signing: signer,
    engine: {
      async applySealingProgress(input) {
        if (engine.refuseProgress) throw new Error('the engine is not running');
        engine.progress.push(structuredClone(input) as SealingProgressInput);
      },
      async completeSeal(input, transcript) {
        engine.completeCalls += 1;
        if (engine.sealed.some((entry) => entry.input.sessionId === input.sessionId && entry.input.manifestSha256 === input.manifestSha256)) return 'ALREADY_SEALED';
        engine.sealed.push({ input: structuredClone(input) as CompleteSealInput, transcript });
        return 'SEALED';
      },
      isSealed: (sessionId, manifestSha256) => engine.sealed.some((entry) => entry.input.sessionId === sessionId && entry.input.manifestSha256 === manifestSha256),
      async noteKeptPlaintext(note) {
        const kept = (engine.kept ??= []);
        if (kept.some((entry) => entry.sessionId === note.sessionId)) return false;
        kept.push(structuredClone(note) as KeptPlaintextNote);
        return true;
      },
    },
    packageDir: () => recording.packageDir,
    stagingDir: () => recording.stagingDir,
    quarantineDir: (sessionId) => join(recording.mediaDir, '.quarantine', sessionId),
    log,
    now: clock.now,
    timer: clock.timer,
    // Small reads: several chunks per fragment and per clear range.
    chunkBytes: 512,
  };
  Object.assign(harness, { ports, pipeline: createSealingPipeline(ports) });
  return harness;
}

