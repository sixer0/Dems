    const markedHaystacks = [readFileSync(markedDownload.archive), ...filesBelow(markedDownload.unpacked).map((file) => readFileSync(join(markedDownload.unpacked, file)))];
    expect(markedHaystacks.some((bytes) => needles.some((needle) => bytes.includes(needle)))).toBe(false);
