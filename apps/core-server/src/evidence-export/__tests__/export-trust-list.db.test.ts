async function signedIn(app: FastifyInstance, username: string): Promise<Record<string, string>> {
  const answer = await webSignIn(app, username);
  expect(answer.statusCode).toBe(200);
  const token = cookieValue(answer, app.config.sessionCookieName);
  if (token === null) throw new Error('the web sign-in set no session cookie');
  return { cookie: `${app.config.sessionCookieName}=${token}`, origin: WEB_ORIGIN };
}

const failureRows = async (evidenceId: string): Promise<Record<string, unknown>[]> =>
  (await db.ownerPool().query<{ details: Record<string, unknown> }>("SELECT details FROM public.audit_log WHERE evidence_id = $1 AND type = 'EVIDENCE_EXPORT_FAILED' ORDER BY seq", [evidenceId])).rows.map((row) => row.details);

const findingsOf = (result: ReceiverVerifyResult): string[] => result.checks.flatMap((check) => check.findings.map((finding) => `${check.id}:${finding}`));

/** Every file below a folder, `/` separated. */
function filesBelow(dir: string, relative = ''): string[] {
  return readdirSync(relative === '' ? dir : join(dir, relative), { withFileTypes: true }).flatMap((entry) => {
    const path = relative === '' ? entry.name : `${relative}/${entry.name}`;
    return entry.isDirectory() ? filesBelow(dir, path) : [path];
  });
}

/** The private-key encodings the signer handles, as needles (the unit test of this row states them one by one). */
function privateKeyNeedles(dataDir: string): Buffer[] {
  const needles: Buffer[] = [Buffer.from('PRIVATE KEY'), Buffer.from('302e020100300506032b657004220420', 'hex'), Buffer.from('MC4CAQAwBQYDK2VwBCIEI')];
  const dir = sealingSignerDir(dataDir);
  let keyFiles = 0;
  for (const name of readdirSync(dir)) {
    if (!/\.(?:p8|wrap)$/.test(name)) continue;
    keyFiles += 1;
    const bytes = readFileSync(join(dir, name));
    needles.push(bytes, Buffer.from(bytes.toString('hex')), Buffer.from(bytes.toString('base64')));
    for (let at = 0; at + 24 <= bytes.byteLength; at += 24) needles.push(bytes.subarray(at, at + 24));
  }
  // Both keys of the store, each with its secret.
  expect(keyFiles).toBe(4);
  return needles;
}

