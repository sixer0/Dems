/**
 * WHICH CORE A SEED COMMAND SEEDS FOR (integration pass E3 item 6). The command line only.
 *
 * `db:seed` and `db:reset` write a database; the v2 demo packages belong to the CORE that will run
 * on it - its evidence store, its credential store, its development signing key. A command knows
 * that Core the way the Core knows itself: from the ENVIRONMENT it is started with and the data
 * directory, read by the Core's own loader (`loadConfig`) and decided by the one function that
 * decides the capture operation (`captureOperationOf`). No flag is read here.
 *
 *   capture operation REAL_DEVELOPMENT   the Core can hold v2 packages of development sources and
 *                                        signs with the development key: the port is the seeder of
 *                                        `sealing-host` over that Core's directories, with the
 *                                        helper program of the configuration;
 *   anything else                        SIMULATED holds no v2 package (operation 41 is the hosted
 *                                        verify there); REAL_PRODUCTION holds no demo data. The port
 *                                        answers SKIPPED with the reason, and the seed writes the
 *                                        dataset as it is.
 *
 * THE HELPER PROGRAM. When the configured helper is absent (or cannot be started) the port answers
 * SKIPPED and NAMES it - path and how to make the copy - and the seed goes on WITHOUT the v2 demo
 * items. Nothing is generated by another program, and no device is involved: the argument table
 * names generated inputs only.
 */
import { captureOperationOf } from '../../capture/fence';
import { ConfigError } from '../../config';
import { loadConfig } from '../../plugins/config';
import type { SeedDemoOutcome, SeedDemoPackages, SeedDemoPlacement, SeedDemoReport } from './demo-packages';
import { SeedHelperProblem, runSeedHelper, seedHelperProblemOf } from './demo-helper';

/** The capture operation whose Core holds seed-sealed demo packages. A literal of the fence's own type. */
const DEVELOPMENT_OPERATION: ReturnType<typeof captureOperationOf> = 'REAL_DEVELOPMENT';

export interface DemoCoreEnvironment {
  /** The environment of the Core this database is seeded for. The command line passes its own. */
  readonly environment: Readonly<Record<string, string | undefined>>;
  /** The Core's data directory. Default: the repository's `.data`. */
  readonly dataDir?: string | undefined;
  /** The seed's one clock reading. */
  readonly now: () => number;
}

/** A port that seals nothing and says why. */
function skipping(reason: string, message: string): SeedDemoPackages {
  const outcome: SeedDemoOutcome = { status: 'SKIPPED', reason, message };
  return { seal: async () => outcome, place: async () => ({ placed: [], notPlaced: [] }), discard: async () => {} };
}

/** The demo-package port of a seed command for the Core of that environment. Never throws. */
export function demoPackagesOfEnvironment(input: DemoCoreEnvironment): SeedDemoPackages {
  let config: ReturnType<typeof loadConfig>;
  try {
    config = loadConfig({ env: input.environment, ...(input.dataDir === undefined ? {} : { dataDir: input.dataDir }) });
  } catch (error) {
    return skipping('CORE_CONFIGURATION_UNREADABLE', `the configuration of the Core of this environment cannot be read (${error instanceof ConfigError ? error.code : 'unexpected failure'})`);
  }
  const operation = captureOperationOf(config);
  if (operation !== DEVELOPMENT_OPERATION) {
    return skipping('NOT_A_DEVELOPMENT_CAPTURE_CORE', `the capture operation of this environment is ${operation}: only a development-capture Core (${DEVELOPMENT_OPERATION}) holds seed-sealed v2 demo packages`);
  }
  const program = config.captureHelperFfmpegPath;
  const problem = seedHelperProblemOf(program);
  if (problem !== null || program === null) {
    return skipping(
      problem ?? SeedHelperProblem.NOT_SET,
      program === null || program === ''
        ? 'no helper program is configured for this environment (DEMS_CAPTURE_HELPER_FFMPEG): the generated picture of a demo package cannot be made'
        : `the helper program ${program} cannot be started (${String(problem)}): make the copy with "node scripts/capture/dev-setup.mjs"`,
    );
  }
  const { dataDir, mediaStoreDir } = config;
  // The sealing composition is loaded only when it is used: a seed for a simulated Core loads none of it.
  let seeder: Promise<SeedDemoPackages> | null = null;
  const load = (): Promise<SeedDemoPackages> =>
    (seeder ??= import('../../sealing-host').then(({ createDemoPackageSeeder }) =>
      createDemoPackageSeeder(
        { dataDir, mediaStoreDir },
        {
          synthesise: ({ args }) => runSeedHelper(program, args),
          now: input.now,
          // A command has no error log file of its own: the reason of a failed generation is in the outcome it prints.
          log: { file: null, append: () => {} },
        },
      ),
    ));
  return {
    seal: async (items, context) => (await load()).seal(items, context),
    place: async () => (seeder === null ? { placed: [], notPlaced: [] } : (await seeder).place()),
    discard: async () => {
      if (seeder !== null) await (await seeder).discard();
    },
  };
}

/** The lines a seed command prints about its v2 demo items. Identifiers and codes; never a digest in full, never a key. */
export function seedDemoLines(report: SeedDemoReport, placement: SeedDemoPlacement | null): { readonly out: string[]; readonly err: string[] } {
  if (report.status === 'NOT_ASKED') return { out: [], err: [] };
  if (report.status === 'SKIPPED') {
    return { out: [`v2 demo packages: NOT generated (${report.reason ?? 'unknown'}): ${report.message ?? ''}. The dataset was written without the v2 demo items; every demo item keeps its v1 shape.`], err: [] };
  }
  const out = [
    `v2 demo packages: ${report.items.length} sealed with the development key from generated sources: ${report.items.map((item) => `${item.evidenceId} (${item.sessionId}${item.tampered ? ', one fragment altered after the seal' : ', clean'})`).join('; ')}`,
  ];
  const err: string[] = [];
  if (placement !== null) {
    if (placement.placed.length > 0) out.push(`v2 demo packages: in the evidence store: ${placement.placed.join(', ')}`);
    for (const left of placement.notPlaced) {
      err.push(`v2 demo packages: ${left.directory} was NOT put in place (${left.reason}): the item row names a package that is not there. Remove the folder that is in the way and reset again.`);
    }
  }
  return { out, err };
}
