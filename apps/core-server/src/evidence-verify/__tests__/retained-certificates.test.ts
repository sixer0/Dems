// Task 4 row 227 (package X1-4; security review SX-09 (c), (d); Known limit 30): THE CORE'S OWN VERIFY
// AND THE RETAINED CERTIFICATE SET.
//
//   (c)  the trust set is every certificate of `<dataDir>/signer` whose key is or was the active
//        one, parsed and self-verified by the store (`readRetainedCertificates`; its own test is
//        `capture/signer/__tests__/retained-certificates.test.ts`). A package sealed under the
//        EARLIER certificate verifies after a rotation. A DEVELOPMENT-marked certificate is never
//        in the trust set of a REAL_PRODUCTION Core.
//   (d)  a package under a key MARKED COMPROMISED is never a plain pass: the named state
//        `COMPROMISED_KEY_STORED_DIGEST` (a pass) only where its manifest digest is the one the
//        Core's database stored - and, with revisions, the head of their chain is the stored one;
//        every other package under that key is a FAILURE, `COMPROMISED_KEY_NOT_STORED_DIGEST`.
//
// The verification is the product's (`createRealEvidenceVerification`) over packages the row-85
// builder seals with keys of a store this test makes; the trust lists are the product's
// (`sealingVerifyTrust`), exactly as `sealing-host/index.ts` hands them over.
//
// SECRETS: every key is generated by this test in a temporary directory that `afterAll` removes
// and asserts gone. The "thief" of a compromised key is the test itself, signing BEFORE the mark.
import { EvidenceVerifyResultSchema } from '@dems/shared/api';
import { ROLE_PERMISSIONS } from '@dems/shared/sim';
import { chmodSync, lstatSync, mkdirSync, mkdtempSync, realpathSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { ACTIVE_KEY_POINTER_NAME, activateSigningKey, markSigningKeyCompromised, provisionSigningKey, type LoadedSigner } from '../../capture';
import type { Principal } from '../../plugins/authenticate';
import { isDevelopmentSigningCertificate, loadSealingSigner, provisionDevelopmentSigningKey, sealingSignerDir, sealingVerifyTrust } from '../../sealing';
import { COMPROMISED_KEY_NOTICE_CODE, COMPROMISED_KEY_NOTICE_REPORT, createRealEvidenceVerification, type RealEvidenceItem, type RealVerificationOptions, type VerdictRecord } from '../index';
import { NOW, buildPackage, removeScratch, type BuiltPackage } from './support';

const OPERATOR: Principal = { kind: 'OPERATOR', operatorId: 'OPR-001', sessionId: 'session', deviceId: null, role: 'INVESTIGATOR', permissions: ROLE_PERMISSIONS.INVESTIGATOR };
const AT = 1_791_600_000_000;
const FIRST = 'CORE-KEY-EVSIGN-01';
const SECOND = 'CORE-KEY-EVSIGN-02';
const THIRD = 'CORE-KEY-EVSIGN-03';
/** Before the builder's signing instant, so every certificate covers it. */
const PROVISIONED = NOW - 100_000;

const roots: string[] = [];
function dataDirectory(): string {
  const root = mkdtempSync(join(realpathSync(tmpdir()), 'dems-row227-verify-'));
  roots.push(root);
  const dataDir = join(root, 'data');
  mkdirSync(dataDir, { mode: 0o700 });
  return dataDir;
}
afterAll(() => {
  removeScratch();
  for (const root of roots) rmSync(root, { recursive: true, force: true });
  for (const root of roots) expect(() => lstatSync(root)).toThrow();
});

/** The Core's verify of ONE item, with the trust lists a Core of that operation reads from its store at each run. */
function coreVerify(dataDir: string, production: boolean, item: RealEvidenceItem, packageOf: BuiltPackage, overrides: Partial<RealVerificationOptions> = {}) {
  const recorded: VerdictRecord[] = [];
  const verification = createRealEvidenceVerification({
    findItem: (evidenceId) => (evidenceId === item.evidenceId ? item : null),
    packageDirOf: () => packageOf.dir,
    now: () => AT,
    opener: packageOf.opener,
    trustedCertificateSha256: () => sealingVerifyTrust({ dataDir, production }).trusted,
    compromisedCertificateSha256: () => sealingVerifyTrust({ dataDir, production }).compromised,
    record: async (_principal, verdict) => void recorded.push(verdict),
    chunkBytes: 512,
    ...overrides,
  });
  return {
    recorded,
    run: async () => {
      const run = await verification.run(OPERATOR, item.evidenceId);
      if (run === null) throw new Error('no run');
      // Whatever the state, the answer is one the contract of operation 41 takes.
      EvidenceVerifyResultSchema.parse(run.body);
      return run;
    },
  };
}

const failureCodes = (run: { report: { checks: readonly { findings: readonly { code: string }[] }[] } }): string[] => [...new Set(run.report.checks.flatMap((check) => check.findings.map((finding) => finding.code)))].sort();
const noticeCodes = (run: { body: { notices?: readonly { code: string }[] | undefined } }): string[] => (run.body.notices ?? []).map((notice) => notice.code);

/** A production-like store (no development mark) with its first key, and the signer of a Core started on it. */
function productionStore(): { dataDir: string; first: LoadedSigner } {
  const dataDir = dataDirectory();
  provisionSigningKey({ dir: sealingSignerDir(dataDir), now: PROVISIONED, subject: { organization: 'SYNTHETIC TEST ORG - NOT AN INSTALLATION', organizationalUnit: 'Evidence signing DEMS-TEST-227' } });
  return { dataDir, first: loadSealingSigner({ dataDir, now: NOW }) };
}
function rotate(dataDir: string, keyId: string): LoadedSigner {
  const dir = sealingSignerDir(dataDir);
  provisionSigningKey({ dir, now: PROVISIONED, keyId, subject: { organization: 'SYNTHETIC TEST ORG - NOT AN INSTALLATION', organizationalUnit: 'Evidence signing DEMS-TEST-227' } });
  activateSigningKey({ dir, keyId, now: NOW });
  return loadSealingSigner({ dataDir, now: NOW });
}

describe('row 227, SX-09 (c): the retained certificate set in the Core\'s own verify', () => {
  it('a package sealed under the EARLIER certificate verifies after a rotation - a plain pass, as the package of the new key', async () => {
    const { dataDir, first } = productionStore();
    const earlier = await buildPackage({ signer: first });
    expect((await coreVerify(dataDir, true, earlier.item, earlier).run()).body.ok).toBe(true);

    const second = rotate(dataDir, SECOND);
    expect(second.signer.keyId).toBe(SECOND);
    const trust = sealingVerifyTrust({ dataDir, production: true });
    expect([...trust.trusted].sort()).toEqual([first.certificate.sha256, second.certificate.sha256].sort());
    expect(trust.compromised).toEqual([]);

    const afterRotation = await coreVerify(dataDir, true, earlier.item, earlier).run();
    expect(afterRotation.body).toMatchObject({ ok: true, overall: 'PASS', signatureOk: true, manifestOk: true });
    expect(afterRotation.signingKey).toBe('NOT_COMPROMISED');
    expect(noticeCodes(afterRotation)).not.toContain(COMPROMISED_KEY_NOTICE_CODE);
    // CONTROL - what the Core did before this row (the active certificate alone): the same package fails.
    const activeOnly = await coreVerify(dataDir, true, earlier.item, earlier, { trustedCertificateSha256: () => [second.certificate.sha256], compromisedCertificateSha256: () => [] }).run();
    expect(activeOnly.body.ok).toBe(false);
    expect(failureCodes(activeOnly)).toEqual(['CERTIFICATE_NOT_TRUSTED']);

    // A package of the new key, and one with a revision signed under the earlier key.
    const later = await buildPackage({ signer: second, sessionId: 'SES-20261009-0227', evidenceId: 'EV-20261009-0227' });
    expect((await coreVerify(dataDir, true, later.item, later).run()).body.ok).toBe(true);
  });

  it('a key that was provisioned and never active, and a certificate of no key of this store, are not trusted', async () => {
    const { dataDir, first } = productionStore();
    rotate(dataDir, SECOND);
    // A third key, provisioned and NOT made active: what a rotation leaves that stopped before the pointer moved.
    const dir = sealingSignerDir(dataDir);
    const never = provisionSigningKey({ dir, now: PROVISIONED, keyId: THIRD });
    expect(sealingVerifyTrust({ dataDir, production: true }).trusted).not.toContain(never.sha256);
    expect(sealingVerifyTrust({ dataDir, production: false }).trusted).not.toContain(never.sha256);
    // A package of a key of ANOTHER store: self-consistent, and not trusted here.
    const foreign = await buildPackage();
    const run = await coreVerify(dataDir, true, foreign.item, foreign).run();
    expect(run.body.ok).toBe(false);
    expect(failureCodes(run)).toEqual(['CERTIFICATE_NOT_TRUSTED']);
    expect(run.signingKey).toBe('NOT_COMPROMISED');
    expect(first.signer.keyId).toBe(FIRST);
  });

  it('a DEVELOPMENT-marked certificate is never in the trusted list of a REAL_PRODUCTION Core - alone, beside a production key, and marked compromised', async () => {
    const dataDir = dataDirectory();
    const development = provisionDevelopmentSigningKey({ dataDir, now: PROVISIONED });
    expect(isDevelopmentSigningCertificate(development)).toBe(true);
    const developmentSigner = loadSealingSigner({ dataDir, now: NOW });
    const built = await buildPackage({ signer: developmentSigner });

    // A development Core trusts its development key, as before.
    expect(sealingVerifyTrust({ dataDir, production: false })).toEqual({ trusted: [development.sha256], compromised: [] });
    expect((await coreVerify(dataDir, false, built.item, built).run()).body).toMatchObject({ ok: true, signature: { developmentKey: true } });
    // A production Core on the same store trusts nothing of it.
    expect(sealingVerifyTrust({ dataDir, production: true })).toEqual({ trusted: [], compromised: [] });
    const refused = await coreVerify(dataDir, true, built.item, built).run();
    expect(refused.body.ok).toBe(false);
    expect(failureCodes(refused)).toEqual(['CERTIFICATE_NOT_TRUSTED']);

    // Beside a production key that became the active one: still not trusted; the production one is.
    const production = rotate(dataDir, SECOND);
    expect(sealingVerifyTrust({ dataDir, production: true })).toEqual({ trusted: [production.certificate.sha256], compromised: [] });
    expect([...sealingVerifyTrust({ dataDir, production: false }).trusted].sort()).toEqual([development.sha256, production.certificate.sha256].sort());
    expect((await coreVerify(dataDir, true, built.item, built).run()).body.ok).toBe(false);

    // Marked compromised: in NEITHER list of a production Core - the compromised path does not let it in by another door.
    markSigningKeyCompromised({ dir: sealingSignerDir(dataDir), keyId: FIRST, at: NOW });
    expect(sealingVerifyTrust({ dataDir, production: true })).toEqual({ trusted: [production.certificate.sha256], compromised: [] });
    const marked = await coreVerify(dataDir, true, built.item, built).run();
    expect(marked.body.ok).toBe(false);
    expect(marked.signingKey).toBe('NOT_COMPROMISED');
    expect(failureCodes(marked)).toEqual(['CERTIFICATE_NOT_TRUSTED']);
  });

  it('FAIL CLOSED: a store that cannot be taken trusts nothing', async () => {
    const { dataDir, first } = productionStore();
    const built = await buildPackage({ signer: first });
    rotate(dataDir, SECOND);
    const pointer = join(sealingSignerDir(dataDir), ACTIVE_KEY_POINTER_NAME);
    chmodSync(pointer, 0o644);
    expect(sealingVerifyTrust({ dataDir, production: true })).toEqual({ trusted: [], compromised: [] });
    const run = await coreVerify(dataDir, true, built.item, built).run();
    expect(run.body.ok).toBe(false);
    expect(failureCodes(run)).toEqual(['CERTIFICATE_NOT_TRUSTED']);
    chmodSync(pointer, 0o600);
    expect((await coreVerify(dataDir, true, built.item, built).run()).body.ok).toBe(true);
    // No store at all.
    expect(sealingVerifyTrust({ dataDir: dataDirectory(), production: true })).toEqual({ trusted: [], compromised: [] });
  });
});

describe('row 227, SX-09 (d): a package under a key marked compromised is never a plain pass', () => {
  it('the package the database stored gets the NAMED STATE and passes; a package with another digest under the same key FAILS', async () => {
    const { dataDir, first } = productionStore();
    const sealed = await buildPackage({ signer: first });
    // What the holder of the key could make: another package of the same item, validly signed with the SAME key, its own session key, wholly consistent.
    const forged = await buildPackage({ signer: first });
    expect(forged.item.evidenceId).toBe(sealed.item.evidenceId);
    expect(forged.item.manifestSha256).not.toBe(sealed.item.manifestSha256);
    const second = rotate(dataDir, SECOND);
    const sound = await buildPackage({ signer: second, sessionId: 'SES-20261009-0228', evidenceId: 'EV-20261009-0228' });
    // Before the mark both would verify as their own item: the key is trusted.
    expect((await coreVerify(dataDir, true, forged.item, forged).run()).body.ok).toBe(true);

    markSigningKeyCompromised({ dir: sealingSignerDir(dataDir), keyId: FIRST, at: NOW + 1 });
    expect(sealingVerifyTrust({ dataDir, production: true })).toEqual({ trusted: [second.certificate.sha256], compromised: [first.certificate.sha256] });

    // THE STORED DIGEST: a pass - with the named state, in the run and in the answer.
    const stored = coreVerify(dataDir, true, sealed.item, sealed);
    const pass = await stored.run();
    expect(pass.signingKey).toBe('COMPROMISED_KEY_STORED_DIGEST');
    expect(pass.body).toMatchObject({ ok: true, overall: 'PASS', manifestOk: true, signatureOk: true });
    expect(pass.body.notices).toContainEqual({ code: COMPROMISED_KEY_NOTICE_CODE, report: COMPROMISED_KEY_NOTICE_REPORT.COMPROMISED_KEY_STORED_DIGEST });
    expect(stored.recorded).toEqual([expect.objectContaining({ ok: true, at: AT })]);
    // Row V5 (C84 R-1): THE RECORD of that pass carries the notice - the audit row and the custody entry are made from it, never as a plain pass.
    expect(stored.recorded[0]?.notice).toBe('SIGNED_BY_COMPROMISED_KEY');

    // ANOTHER DIGEST under the same key, in the item's folder: a failure, by name.
    const swapped = coreVerify(dataDir, true, sealed.item, forged);
    const fail = await swapped.run();
    expect(fail.signingKey).toBe('COMPROMISED_KEY_NOT_STORED_DIGEST');
    expect(fail.body.ok).toBe(false);
    expect(fail.body.manifestOk).toBe(false);
    expect(failureCodes(fail)).toContain('MANIFEST_NOT_OF_ITEM');
    expect(fail.body.notices).toContainEqual({ code: COMPROMISED_KEY_NOTICE_CODE, report: COMPROMISED_KEY_NOTICE_REPORT.COMPROMISED_KEY_NOT_STORED_DIGEST });
    expect(swapped.recorded).toEqual([expect.objectContaining({ ok: false })]);
    expect(swapped.recorded[0]?.notice).toBe('SIGNED_BY_COMPROMISED_KEY');
    // The forged package against "its own" digest is what an attacker would need the DATABASE for: here the database says otherwise.
    // An item whose stored digest is no digest anchors nothing: a failure.
    const unanchored = await coreVerify(dataDir, true, { ...sealed.item, manifestSha256: '' }, sealed).run();
    expect(unanchored.body.ok).toBe(false);
    expect(unanchored.signingKey).toBe('COMPROMISED_KEY_NOT_STORED_DIGEST');

    // A caller that hands over NO compromised list: the certificate is simply not trusted - a failure, never a pass.
    const without = await coreVerify(dataDir, true, sealed.item, sealed, { compromisedCertificateSha256: undefined as never }).run();
    expect(without.body.ok).toBe(false);
    expect(failureCodes(without)).toEqual(['CERTIFICATE_NOT_TRUSTED']);

    // A package of the SOUND key is a plain pass while another key of the store is marked.
    const plain = await coreVerify(dataDir, true, sound.item, sound).run();
    expect(plain.signingKey).toBe('NOT_COMPROMISED');
    expect(plain.body.ok).toBe(true);
    expect(noticeCodes(plain)).not.toContain(COMPROMISED_KEY_NOTICE_CODE);
    // Row V5: and its record has NO such member - a verdict no mark played a part in is recorded exactly as before.
    const plainRun = coreVerify(dataDir, true, sound.item, sound);
    await plainRun.run();
    expect(Object.keys(plainRun.recorded[0] ?? {}).sort()).toEqual(['at', 'detail', 'evidenceId', 'failedFragments', 'failedTracks', 'manifestOk', 'ok', 'signatureOk']);
  });

  it('transcript revisions under the compromised key: a pass only where the head of the chain is the one the database holds', async () => {
    const { dataDir, first } = productionStore();
    const sealed = await buildPackage({ signer: first, revisions: 2 });
    expect(sealed.item.revisionCount).toBe(2);
    const { TranscriptRevisionsFileSchema } = await import('@dems/shared/evidence-verify');
    const { readFileSync } = await import('node:fs');
    const head = TranscriptRevisionsFileSchema.parse(JSON.parse(readFileSync(sealed.path('transcript/transcript-revisions.json'), 'utf8'))).revisions.at(-1)?.sha256 ?? '';
    expect(head).toMatch(/^[0-9a-f]{64}$/);
    rotate(dataDir, SECOND);
    markSigningKeyCompromised({ dir: sealingSignerDir(dataDir), keyId: FIRST, at: NOW + 1 });

    // The database holds this head: the named state, a pass.
    const anchored = await coreVerify(dataDir, true, { ...sealed.item, revisionHeadSha256: head }, sealed).run();
    expect(anchored.signingKey).toBe('COMPROMISED_KEY_STORED_DIGEST');
    expect(anchored.body).toMatchObject({ ok: true, transcriptOk: true });
    // The database holds ANOTHER head (a revision re-made with the compromised key, same count): a failure.
    const other = await coreVerify(dataDir, true, { ...sealed.item, revisionHeadSha256: 'ab'.repeat(32) }, sealed).run();
    expect(other.signingKey).toBe('COMPROMISED_KEY_NOT_STORED_DIGEST');
    expect(other.body.ok).toBe(false);
    expect(failureCodes(other)).toEqual(['CERTIFICATE_NOT_TRUSTED', 'REVISION_CERTIFICATE_NOT_TRUSTED']);
    // The head not stated at all: nothing is anchored - a failure.
    const unstated = await coreVerify(dataDir, true, sealed.item, sealed).run();
    expect(unstated.signingKey).toBe('COMPROMISED_KEY_NOT_STORED_DIGEST');
    expect(unstated.body.ok).toBe(false);
    for (const run of [other, unstated]) expect(run.body.notices).toContainEqual({ code: COMPROMISED_KEY_NOTICE_CODE, report: COMPROMISED_KEY_NOTICE_REPORT.COMPROMISED_KEY_NOT_STORED_DIGEST });
  });
});
