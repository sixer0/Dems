/**
 * DEMO asset resolution for the Evidence page (D50, D67; implementation/65_demo_evidence.md §4,
 * F-93-1; review 40 rule R2 / finding M2).
 *
 * Every media, metadata, integrity and export file is resolved from the step-93 package index
 * (`tracks[].stored.path`, `tracks[].poster|thumbnail.path`, `files.*`, `export.*`), never from a
 * folder convention: the tampered EV 0005 stores its altered AUDIO-02 inside its package folder, and
 * the recording-scenario item EV 0014 points at the live loops. All paths are relative to
 * `packages/shared/assets/`; ONE glob covers both folders the index points into:
 * - `demo-media/evidence/**` and `demo-media/live/*`: the step-92 videos, MIC tracks and stills
 *   (the mobile subset `demo-media/mobile/**` is never shipped to the web);
 * - `demo-evidence/**`: manifest, metadata, signature, certificate, audit extract, the altered copy,
 *   and the EV 0004 export zip and export manifest.
 *
 * Why a workspace-relative glob: Vite 8 rejects a bare package specifier in a glob (D70). `?url`
 * keeps only URL strings in this lazy page chunk; bytes are fetched on demand (Verify, Download).
 * The loader is injectable through `EvidenceAssetsContext`, so tests read the same files from disk
 * and pass Node's WebCrypto explicitly.
 *
 * DR-47-3: Vite's default `server.fs.deny` refuses `*.pem` (and `*.crt`) in development, so the
 * package's `device-certificate.pem` is not globbed; the loader serves the PEM text of the same file
 * from `DEMO_DEVICE_CERTIFICATE_PEM` (generated by step 93 from that file; one certificate for every
 * package). The certificate check still recomputes the DER fingerprint and self-signature; a test
 * asserts that the module text equals the file on disk byte for byte.
 */
import { createContext, useContext } from 'react'
import { DEMO_DEVICE_CERTIFICATE_PEM, type DemoAssetLoader, type SubtleLike } from '@dems/shared/demo-data'

const DEMO_FILES = import.meta.glob<string>(
  [
    '../../../../../packages/shared/assets/demo-media/evidence/*/*.{mp4,m4a,jpg}',
    '../../../../../packages/shared/assets/demo-media/live/*.{mp4,m4a,jpg}',
    '../../../../../packages/shared/assets/demo-evidence/**/*.{json,sig,jsonl,zip,m4a}',
  ],
  { query: '?url', import: 'default', eager: true },
)

const ASSET_ROOT_MARKER = 'packages/shared/assets/'

/** `demo-evidence/SESSION-…/manifest.json` or `demo-media/evidence/0001/VIDEO-01.mp4` → URL. */
const ASSET_URLS: ReadonlyMap<string, string> = new Map(
  Object.entries(DEMO_FILES).map(([key, url]) => [
    key.slice(key.lastIndexOf(ASSET_ROOT_MARKER) + ASSET_ROOT_MARKER.length),
    url,
  ]),
)

/** URL of a DEMO asset (a path relative to packages/shared/assets/), or null when it is not bundled. */
export function demoAssetUrlFor(assetPath: string | null | undefined): string | null {
  if (!assetPath) return null
  return ASSET_URLS.get(assetPath.replace(/^\/+/, '')) ?? null
}

/** A DEMO asset could not be loaded (not bundled, or the dev server answered with an error). */
export class DemoAssetError extends Error {
  readonly assetPath: string
  readonly status: number | null

  constructor(assetPath: string, status: number | null, message: string) {
    super(message)
    this.name = 'DemoAssetError'
    this.assetPath = assetPath
    this.status = status
  }
}

type FetchLike = (url: string) => Promise<Response>

const CERTIFICATE_FILE = '/device-certificate.pem'

/** True for a package certificate path (served from the demo-data module, DR-47-3). */
export function isCertificatePath(assetPath: string): boolean {
  return assetPath.startsWith('demo-evidence/') && assetPath.endsWith(CERTIFICATE_FILE)
}

/** A `DemoAssetLoader` that fetches the bundled URL and returns the bytes. */
export function createFetchLoader(fetchImpl: FetchLike = (url) => fetch(url)): DemoAssetLoader {
  return async (assetPath) => {
    if (isCertificatePath(assetPath)) return new TextEncoder().encode(DEMO_DEVICE_CERTIFICATE_PEM)
    const url = demoAssetUrlFor(assetPath)
    if (!url) throw new DemoAssetError(assetPath, null, `DEMO asset not bundled: ${assetPath}`)
    const response = await fetchImpl(url)
    if (!response.ok) throw new DemoAssetError(assetPath, response.status, `HTTP ${response.status} for ${assetPath}`)
    return new Uint8Array(await response.arrayBuffer())
  }
}

export interface EvidenceAssetsValue {
  /** Loads the bytes of a DEMO asset. */
  load: DemoAssetLoader
  /** WebCrypto for the Ed25519 checks; undefined = the runtime's `crypto.subtle`. */
  subtle?: SubtleLike | null
  /** Resolves a DEMO asset path to a URL (media `src`, posters). */
  urlFor: (assetPath: string | null | undefined) => string | null
}

const DEFAULT_ASSETS: EvidenceAssetsValue = {
  load: createFetchLoader(),
  urlFor: demoAssetUrlFor,
}

export const EvidenceAssetsContext = createContext<EvidenceAssetsValue>(DEFAULT_ASSETS)

export function useEvidenceAssets(): EvidenceAssetsValue {
  return useContext(EvidenceAssetsContext)
}
